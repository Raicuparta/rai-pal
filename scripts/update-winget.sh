#!/usr/bin/env bash
set -euo pipefail

TAG="${1:-}"
if [[ -z "$TAG" ]]; then
	echo "Usage: $0 <release-tag>" >&2
	exit 1
fi

VERSION="${TAG#v}"
IDENTIFIER="Raicuparta.RaiPal"
RELEASE_REPO="Raicuparta/rai-pal"
UPSTREAM_REPO="microsoft/winget-pkgs"
MANIFEST_VERSION="1.12.0"
INSTALLER_URL="https://github.com/$RELEASE_REPO/releases/download/$TAG/RaiPal.exe"
BRANCH="$IDENTIFIER-$VERSION"

IDENTIFIER_LOWER="$(tr '[:upper:]' '[:lower:]' <<<"$IDENTIFIER")"
PACKAGE_PATH="manifests/${IDENTIFIER_LOWER:0:1}/${IDENTIFIER//./\/}"
VERSION_PATH="$PACKAGE_PATH/$VERSION"

VERSION_FILE="$IDENTIFIER.yaml"
INSTALLER_FILE="$IDENTIFIER.installer.yaml"
LOCALE_FILE="$IDENTIFIER.locale.en-US.yaml"

FORK_REPO_NAME="${UPSTREAM_REPO#*/}"
FORK_OWNER="$(gh api user --jq .login)"
FORK_API="repos/$FORK_OWNER/$FORK_REPO_NAME"

RELEASE_DATE="$(gh api "repos/$RELEASE_REPO/releases/tags/$TAG" --jq '.published_at // .created_at' | cut -c1-10)"

TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

echo "Downloading $INSTALLER_URL"
curl -fsSL --retry 3 -o "$TMP_DIR/RaiPal.exe" "$INSTALLER_URL"
INSTALLER_SHA256="$(sha256sum "$TMP_DIR/RaiPal.exe" | cut -d' ' -f1 | tr '[:lower:]' '[:upper:]')"

cat >"$TMP_DIR/$VERSION_FILE" <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.$MANIFEST_VERSION.schema.json

PackageIdentifier: $IDENTIFIER
PackageVersion: $VERSION
DefaultLocale: en-US
ManifestType: version
ManifestVersion: $MANIFEST_VERSION
EOF

cat >"$TMP_DIR/$INSTALLER_FILE" <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.$MANIFEST_VERSION.schema.json

PackageIdentifier: $IDENTIFIER
PackageVersion: $VERSION
InstallerType: nullsoft
Scope: machine
InstallerSwitches:
  Silent: /S
  SilentWithProgress: /S
ProductCode: Rai Pal
ReleaseDate: $RELEASE_DATE
AppsAndFeaturesEntries:
- Publisher: raicuparta
  ProductCode: Rai Pal
Installers:
- Architecture: x64
  InstallerUrl: $INSTALLER_URL
  InstallerSha256: $INSTALLER_SHA256
ManifestType: installer
ManifestVersion: $MANIFEST_VERSION
EOF

{
	cat <<EOF
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.$MANIFEST_VERSION.schema.json

PackageIdentifier: $IDENTIFIER
PackageVersion: $VERSION
PackageLocale: en-US
Publisher: Raicuparta
PackageName: Rai Pal
License: GPL-3.0
LicenseUrl: https://github.com/$RELEASE_REPO/blob/HEAD/LICENSE
ShortDescription: Mod manager for universal game mods
Moniker: raipal
ReleaseNotesUrl: https://github.com/$RELEASE_REPO/releases/tag/$TAG
ManifestType: defaultLocale
ManifestVersion: $MANIFEST_VERSION
EOF
} >"$TMP_DIR/$LOCALE_FILE"

if gh api "repos/$UPSTREAM_REPO/contents/$VERSION_PATH" >/dev/null 2>&1; then
	echo "$IDENTIFIER $VERSION already exists in $UPSTREAM_REPO, nothing to do"
	exit 0
fi

OLD_PR="$(gh api "repos/$UPSTREAM_REPO/pulls?state=open&head=$FORK_OWNER:$BRANCH" --jq '.[0].html_url // ""')"
if [[ -n "$OLD_PR" ]]; then
	echo "A pull request for $BRANCH is already open: $OLD_PR"
	exit 0
fi

if ! gh api "$FORK_API" >/dev/null 2>&1; then
	echo "Creating fork $FORK_OWNER/$FORK_REPO_NAME"
	gh api --method POST "repos/$UPSTREAM_REPO/forks" -f default_branch_only=true >/dev/null
	for _ in $(seq 1 60); do
		gh api "$FORK_API" >/dev/null 2>&1 && break
		sleep 5
	done
	gh api "$FORK_API" >/dev/null
fi

BASE_SHA="$(gh api "repos/$UPSTREAM_REPO/git/ref/heads/master" --jq .object.sha)"

gh api --method DELETE "$FORK_API/git/refs/heads/$BRANCH" >/dev/null 2>&1 || true

upload_blob() {
	gh api --method POST "$FORK_API/git/blobs" -f "content=$(base64 -w0 "$1")" -f encoding=base64 --jq .sha
}

tree_entry() {
	printf '{"path":"%s/%s","mode":"100644","type":"blob","sha":"%s"}' "$VERSION_PATH" "$1" "$2"
}

echo "Uploading manifests"
VERSION_BLOB="$(upload_blob "$TMP_DIR/$VERSION_FILE")"
INSTALLER_BLOB="$(upload_blob "$TMP_DIR/$INSTALLER_FILE")"
LOCALE_BLOB="$(upload_blob "$TMP_DIR/$LOCALE_FILE")"

TREE_JSON="$(printf '{"base_tree":"%s","tree":[%s,%s,%s]}' "$BASE_SHA" \
	"$(tree_entry "$VERSION_FILE" "$VERSION_BLOB")" \
	"$(tree_entry "$INSTALLER_FILE" "$INSTALLER_BLOB")" \
	"$(tree_entry "$LOCALE_FILE" "$LOCALE_BLOB")")"
TREE_SHA="$(gh api --method POST "$FORK_API/git/trees" --input - --jq .sha <<<"$TREE_JSON")"

COMMIT_JSON="$(printf '{"message":"Update %s to version %s","tree":"%s","parents":["%s"]}' "$IDENTIFIER" "$VERSION" "$TREE_SHA" "$BASE_SHA")"
COMMIT_SHA="$(gh api --method POST "$FORK_API/git/commits" --input - --jq .sha <<<"$COMMIT_JSON")"

gh api --method POST "$FORK_API/git/refs" --input - --jq .ref >/dev/null <<<"$(printf '{"ref":"refs/heads/%s","sha":"%s"}' "$BRANCH" "$COMMIT_SHA")"

RELEASE_URL="https://github.com/$RELEASE_REPO/releases/tag/$TAG"
PR_BODY="Automated manifest update for [$TAG]($RELEASE_URL), generated by the Rai Pal release pipeline.\n\n- [x] This PR only modifies one (1) manifest\n- [x] Checked that there aren't other open pull requests for the same manifest update"
PR_JSON="$(printf '{"title":"Update: %s to %s","head":"%s:%s","base":"master","body":"%s"}' "$IDENTIFIER" "$VERSION" "$FORK_OWNER" "$BRANCH" "$PR_BODY")"

PR_URL="$(gh api --method POST "repos/$UPSTREAM_REPO/pulls" --input - --jq .html_url <<<"$PR_JSON")"

echo "Opened pull request: $PR_URL"
